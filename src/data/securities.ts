/** Builds a full NSE equity Security from a compact spec (INR, 1-tick spread derived). */
const mkIndianEquity = (s: IndianEquitySpec): Security => {
  const prevClose = +(s.price / (1 + s.chg / 100)).toFixed(2);
  const change = +(s.price - prevClose).toFixed(2);
  const open = +(prevClose * (1 + seedNoise(s.ticker, 1) * 0.004)).toFixed(2);
  const high = +Math.max(s.price, open, prevClose).toFixed(2);
  const low = +Math.min(s.price, open, prevClose).toFixed(2);
  const spread = +Math.max(0.01, s.price * 0.0002).toFixed(2);
  const sparkline = Array.from({ length: 6 }, (_, i) => {
    const t = i / 5;
    const base = prevClose + (s.price - prevClose) * t;
    const wobble = seedNoise(s.ticker, 10 + i) * s.price * 0.0035;
    return +(base + wobble * (1 - t * 0.6)).toFixed(2);
  });
  sparkline[sparkline.length - 1] = s.price;
  return {
    ticker: s.ticker,
    name: s.name,
    assetClass: 'EQUITY',
    exchange: 'NSE',
    currency: 'INR',
    price: s.price,
    change,
    changePercent: s.chg,
    open,
    high,
    low,
    prevClose,
    volume: s.vol,
    avgVolume: Math.round(s.vol * 1.05),
    marketCap: s.mcap,
    peRatio: s.pe,
    fwdPe: s.fpe,
    evEbitda: +(s.pe * 0.68).toFixed(1),
    eps: s.eps,
    divYield: s.dy,
    beta: s.beta,
    fiftyTwoWeekHigh: s.h52,
    fiftyTwoWeekLow: s.l52,
    description: s.desc,
    sector: s.sector,
    industry: s.industry,
    consensusRating: s.rt,
    targetPrice: s.tgt,
    targetHigh: s.th,
    targetLow: s.tl,
    analystCount: s.an,
    sparkline,
    lastUpdate: Date.now(),
    bid: +(s.price - spread).toFixed(2),
    ask: +(s.price + spread).toFixed(2),
    bidSize: Math.round(s.vol / 120),
    askSize: Math.round(s.vol / 105),
  };
};

