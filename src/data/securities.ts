import type { Security } from '../types/terminal';

type ConsensusRating = Security['consensusRating'];

/** Deterministic pseudo-noise in [-1, 1] derived from a ticker + salt. */
function seedNoise(ticker: string, salt: number): number {
  let h = 0;
  const key = `${ticker}:${salt}`;
  for (let i = 0; i < key.length; i++) {
    h = (h * 31 + key.charCodeAt(i)) >>> 0;
  }
  return ((h % 2001) / 1000) - 1;
}

