/** Seeds quote-first NSE additions; Yahoo fills live prices and fundamentals when available. */
const mkIndianQuoteSecurity = (s: IndianQuoteSpec): Security => {
  const prevClose = +(s.price / (1 + s.changePercent / 100)).toFixed(2);
  const change = +(s.price - prevClose).toFixed(2);
  const spread = +Math.max(0.01, s.price * 0.0002).toFixed(2);
  const cap = s.marketCap >= 1_000_000_000_000
    ? `₹${(s.marketCap / 1_000_000_000_000).toFixed(2)}T`
    : `₹${Math.round(s.marketCap / 1_000_000_000)}B`;
  return {
    ticker: s.ticker,
    name: s.name,
    assetClass: 'EQUITY',
    exchange: 'NSE',
    currency: 'INR',
    price: s.price,
    change,
    changePercent: s.changePercent,
    open: prevClose,
    high: Math.max(s.price, prevClose),
    low: Math.min(s.price, prevClose),
    prevClose,
    volume: s.volume,
    avgVolume: s.volume,
    marketCap: cap,
    fiftyTwoWeekHigh: s.price,
    fiftyTwoWeekLow: s.price,
    description: s.description,
    sector: s.sector,
    industry: s.industry,
    // No analyst coverage for quote-first seeds: 0 signals "no target" so
    // DES/ANR render N/A instead of a fake spot-pegged target.
    consensusRating: 'HOLD',
    targetPrice: 0,
    targetHigh: 0,
    targetLow: 0,
    analystCount: 0,
    sparkline: [prevClose, s.price],
    lastUpdate: Date.now(),
    bid: +(s.price - spread).toFixed(2),
    ask: +(s.price + spread).toFixed(2),
    bidSize: Math.round(s.volume / 120),
    askSize: Math.round(s.volume / 105),
  };
};

